export interface ResolutionCheck {
  readonly id: string;
  readonly passed: boolean;
  readonly detail: string;
}

/**
 * Resolution precedence through the real overlay: curator-approved stored
 * translations always win, matching-hash machine rows render with machine
 * provenance, stale hashes are ignored, and curator verdicts on machine
 * rows surface as approved.
 */
export const checkResolution = (): ReadonlyArray<ResolutionCheck> => {
  const checks: Array<ResolutionCheck> = [];
  const target = "en";
  const venue = "Quán fixture";

  const itemHash = localizationSourceFingerprint({
    kind: "item",
    sourceLanguage: "vi",
    target,
    name: "Phở bò",
    description: "Nước dùng từ xương bò ninh nhừ.",
  });

  const offerings = [offeringFixture({})];
  const machineRow = machineRowFixture({ sourceHash: itemHash });

  // Machine tier applies with labeled provenance when nothing approved exists.
  const machineMenu = presentReviewedWithLocalizations(offerings, venue, target, undefined, [
    machineRow,
  ]);

  const machineItem = machineMenu.items[0];

  checks.push({
    id: "machine-applies-below-approved",
    passed:
      machineItem?.translatedName === "Beef noodle soup" &&
      machineItem.translatedNameProvenance === "machine",
    detail: "matching-hash machine row fills the empty approved tier with machine provenance",
  });

  const machineDisplay =
    machineItem === undefined
      ? null
      : menuItemDisplayFor(machineItem, {
          sourceLanguage: "vi",
          targetLanguage: target,
          provenance: "reviewed",
        });

  checks.push({
    id: "machine-display-labels-provenance",
    passed: machineDisplay?.title === "Beef noodle soup" && machineDisplay.provenance === "machine",
    detail: "item display surfaces the machine title under machine provenance",
  });

  // Curator-approved stored translation wins over any machine row.
  const approvedOfferings = [
    offeringFixture({
      translation_language: "en",
      translated_name: "Curator beef noodle soup",
    }),
  ];

  const approvedMenu = presentReviewedWithLocalizations(
    approvedOfferings,
    venue,
    target,
    undefined,
    [machineRow],
  );

  const approvedItem = approvedMenu.items[0];

  checks.push({
    id: "approved-wins-over-machine",
    passed:
      approvedItem?.translatedName === "Curator beef noodle soup" &&
      approvedItem.translatedNameProvenance === "approved",
    detail: "machine row never overwrites the curator-approved tier",
  });

  // Stale hashes are ignored: a source edit retires the row from reads.
  const staleMenu = presentReviewedWithLocalizations(offerings, venue, target, undefined, [
    machineRowFixture({ sourceHash: "0".repeat(64) }),
  ]);

  const staleItem = staleMenu.items[0];

  checks.push({
    id: "stale-hash-ignored",
    passed: staleItem?.translatedName === null,
    detail: "hash mismatch leaves the original text in place",
  });

  // A curator-approved machine suggestion renders as approved.
  const promotedMenu = presentReviewedWithLocalizations(offerings, venue, target, undefined, [
    machineRowFixture({ sourceHash: itemHash, status: "approved" }),
  ]);

  const promotedItem = promotedMenu.items[0];

  checks.push({
    id: "promoted-machine-renders-approved",
    passed:
      promotedItem?.translatedName === "Beef noodle soup" &&
      promotedItem.translatedNameProvenance === "approved",
    detail: "curator verdict on a machine row promotes its provenance",
  });

  // Direct row resolution honors entity, target, and hash together.
  const resolved = resolveMachineLocalization([machineRow], {
    itemId: "00000000-0000-4000-8000-000000000001",
    variantId: null,
    target,
    sourceHash: itemHash,
  });

  const wrongTarget = resolveMachineLocalization([machineRow], {
    itemId: "00000000-0000-4000-8000-000000000001",
    variantId: null,
    target: "ja",
    sourceHash: itemHash,
  });

  checks.push({
    id: "row-resolution-matches-exactly",
    passed: resolved !== null && wrongTarget === null,
    detail: "row lookup requires entity, target, and hash together",
  });

  return checks;
};

export interface LocalizationSummary {
  readonly cases: ReadonlyArray<ScoredCase>;
  readonly probes: ReadonlyArray<ScoredProbe>;
  readonly resolution: ReadonlyArray<ResolutionCheck>;
  readonly passed: boolean;
}

export const summarizeEvaluation = (
  cases: ReadonlyArray<GroundTruthCase>,
  probes: ReadonlyArray<LocalizationProbe>,
): LocalizationSummary => {
  const scored = cases.map(scoreCase);
  const scoredProbes = probes.map(scoreProbe);
  const resolution = checkResolution();

  const passed =
    scored.every((entry) => entry.passed) &&
    scoredProbes.every((entry) => entry.passed) &&
    resolution.every((entry) => entry.passed);

  return { cases: scored, probes: scoredProbes, resolution, passed };
};

export const summaryToJson = (summary: LocalizationSummary): string =>
  JSON.stringify(
    {
      cases: summary.cases.length,
      casesPassed: summary.cases.filter((entry) => entry.passed).length,
      probes: summary.probes.length,
      probesPassed: summary.probes.filter((entry) => entry.passed).length,
      resolution: summary.resolution.length,
      resolutionPassed: summary.resolution.filter((entry) => entry.passed).length,
      passed: summary.passed,
    },
    null,
    2,
  );

export const formatCaseTable = (summary: LocalizationSummary): string => {
  const lines = ["case | keys | shape | safety | pass"];

  for (const entry of summary.cases) {
    lines.push(
      `${entry.id} | ${entry.keyCoverage ? "ok" : "FAIL"} | ${entry.boundsValid ? "ok" : "FAIL"} | ${entry.safetyPassed ? "ok" : "FAIL"} | ${entry.passed ? "ok" : "FAIL"}`,
    );
  }

  for (const entry of summary.probes) {
    lines.push(
      `${entry.id} | probe | ${entry.rejected ? "rejected" : "served"} | - | ${entry.passed ? "ok" : "FAIL"}`,
    );
  }

  for (const entry of summary.resolution) {
    lines.push(
      `${entry.id} | resolution | - | - | ${entry.passed ? "ok" : "FAIL"} (${entry.detail})`,
    );
  }

  return lines.join("\n");
};
