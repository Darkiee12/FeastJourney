/**
 * Offline menu-localization evaluation scorer.
 *
 * Scores the hand-maintained ground truth in
 * tests/fixtures/menu-localizations/cases.json plus the adversarial probes
 * in the same file.
 *
 * What this measures: harness plumbing and response validation (bounds,
 * safety guard, source-hash match, approved-wins precedence) by running
 * hand-written stub outputs through the REAL validators and the REAL
 * presentation overlay. What it does NOT measure: live model translation
 * quality. The stub path never calls a provider, and ground truth is
 * maintained by hand — never generated by the model under test. Reported
 * rates are computed from the fixture inputs only; empty denominators yield
 * null (unevaluated), never 0% or 100%.
 */

