const FIXTURE_DIRECTORY = join(
  dirname(fileURLToPath(import.meta.url)),
  "..",
  "fixtures",
  "menu-localizations",
);

const variantFixtureSchema = z.object({
  variantId: z.string().min(1),
  label: z.string().min(1),
});

const itemFixtureSchema = z.object({
  itemId: z.string().min(1),
  name: z.string().min(1),
  description: z.string(),
  variants: z.array(variantFixtureSchema).min(1),
});

const stubOutputSchema = z.object({
  key: z.string().min(1),
  displayName: z.string().nullable(),
  description: z.string().nullable(),
  explanation: z.string().nullable(),
});

const groundTruthCaseSchema = z.object({
  id: z.string().min(1),
  origin: z.string().min(1),
  humanReviewed: z.boolean(),
  note: z.string().min(1),
  sourceLanguage: z.string().nullable(),
  target: z.string().min(1),
  items: z.array(itemFixtureSchema).min(1),
  stubOutputs: z.array(stubOutputSchema).min(1),
  requiredBehaviors: z.array(z.string().min(1)).min(1),
});

export type GroundTruthCase = z.infer<typeof groundTruthCaseSchema>;

const probeSchema = z.object({
  id: z.string().min(1),
  expectRejected: z.boolean(),
  reason: z.string().min(1),
  source: z.object({ name: z.string().min(1), description: z.string().nullable() }),
  output: stubOutputSchema,
});

export type LocalizationProbe = z.infer<typeof probeSchema>;

const casesFileSchema = z.object({
  cases: z.array(groundTruthCaseSchema).min(1),
  probes: z.array(probeSchema).min(1),
});

export interface GroundTruthFile {
  readonly cases: ReadonlyArray<GroundTruthCase>;
  readonly probes: ReadonlyArray<LocalizationProbe>;
}

export const loadGroundTruthCases = (): GroundTruthFile => {
  const parsed = casesFileSchema.parse(
    JSON.parse(readFileSync(join(FIXTURE_DIRECTORY, "cases.json"), "utf8")),
  );

  return { cases: parsed.cases, probes: parsed.probes };
};

/** Bounds check mirroring the provider-output and table constraints. */
export const checkOutputBounds = (output: LocalizationUnitOutput): boolean => {
  if (output.key.trim() === "") return false;

  for (const field of [output.displayName, output.description, output.explanation]) {
    if (field === null) continue;

    const limit =
      field === output.displayName ? MAX_LOCALIZED_NAME_LENGTH : MAX_LOCALIZED_TEXT_LENGTH;

    if (field.trim() === "" || field.length > limit) return false;
  }

  return true;
};

const toUnit = (
  item: GroundTruthCase["items"][number],
  variant: GroundTruthCase["items"][number]["variants"][number] | null,
  sourceLanguage: string | null,
  target: string,
): LocalizationUnit => {
  let description: string | null = null;

  if (variant === null && item.description.trim() !== "") description = item.description;

  return {
    key: variant === null ? `item:${item.itemId}` : `variant:${variant.variantId}`,
    kind: variant === null ? "item" : "variant",
    itemId: item.itemId,
    variantId: variant?.variantId ?? null,
    sourceLanguage,
    name: variant === null ? item.name : variant.label,
    description,
    sourceHash: localizationSourceFingerprint({
      kind: variant === null ? "item" : "variant",
      sourceLanguage,
      target,
      name: variant === null ? item.name : variant.label,
      description,
    }),
    curatorTranslated: false,
  };
};

export interface ScoredCase {
  readonly id: string;
  readonly keyCoverage: boolean;
  readonly boundsValid: boolean;
  readonly safetyPassed: boolean;
  readonly passed: boolean;
}

/** Key coverage, bounds, and the real safety guard over hand-written stub outputs. */
export const scoreCase = (groundTruth: GroundTruthCase): ScoredCase => {
  const expectedKeys = new Set<string>();
  const units = new Map<string, LocalizationUnit>();

  for (const item of groundTruth.items) {
    const itemUnit = toUnit(item, null, groundTruth.sourceLanguage, groundTruth.target);

    expectedKeys.add(itemUnit.key);
    units.set(itemUnit.key, itemUnit);

    for (const variant of item.variants) {
      const variantUnit = toUnit(item, variant, groundTruth.sourceLanguage, groundTruth.target);

      expectedKeys.add(variantUnit.key);
      units.set(variantUnit.key, variantUnit);
    }
  }

  const seenKeys = new Set<string>();
  let boundsValid = true;
  let safetyPassed = true;

  for (const output of groundTruth.stubOutputs) {
    seenKeys.add(output.key);

    if (!checkOutputBounds(output)) boundsValid = false;

    const unit = units.get(output.key);

    if (unit === undefined) {
      boundsValid = false;
      continue;
    }

    if (!checkUnitSafety(unit, output)) safetyPassed = false;
  }

  const keyCoverage =
    seenKeys.size === expectedKeys.size && [...expectedKeys].every((key) => seenKeys.has(key));

  return {
    id: groundTruth.id,
    keyCoverage,
    boundsValid,
    safetyPassed,
    passed: keyCoverage && boundsValid && safetyPassed,
  };
};

export interface ScoredProbe {
  readonly id: string;
  readonly rejected: boolean;
  readonly passed: boolean;
}

/** Adversarial outputs must be rejected exactly when the fixture says so. */
export const scoreProbe = (probe: LocalizationProbe): ScoredProbe => {
  const boundsOk = checkOutputBounds(probe.output);

  const unit: LocalizationUnit = {
    key: "item:probe",
    kind: "item",
    itemId: "probe",
    variantId: null,
    sourceLanguage: null,
    name: probe.source.name,
    description: probe.source.description,
    sourceHash: "probe",
    curatorTranslated: false,
  };

  const safe = boundsOk && checkUnitSafety(unit, probe.output);
  const rejected = !safe;

  return { id: probe.id, rejected, passed: rejected === probe.expectRejected };
};

