/** Evenly distributes expected amounts across items in order (remainder to earliest items). */
function splitAmounts(
  amounts: ReadonlyArray<string | null>,
  itemCount: number,
): Array<ReadonlyArray<string | null>> {
  const slices: Array<ReadonlyArray<string | null>> = [];

  if (itemCount === 0) return slices;

  const base = Math.floor(amounts.length / itemCount);
  let rest = amounts.length % itemCount;
  let offset = 0;

  for (let index = 0; index < itemCount; index += 1) {
    const extra = rest > 0 ? 1 : 0;

    if (rest > 0) rest -= 1;

    slices.push(amounts.slice(offset, offset + base + extra));
    offset += base + extra;
  }

  return slices;
}

function rate(numerator: number, denominator: number): number | null {
  if (denominator === 0) return null;

  return numerator / denominator;
}

function meanOrNull(values: ReadonlyArray<number | null>): number | null {
  const present: Array<number> = [];

  for (const value of values) {
    if (value !== null) present.push(value);
  }

  if (present.length === 0) return null;

  const total = present.reduce((sum, value) => sum + value, 0);

  return total / present.length;
}

export interface AssociationMetrics {
  readonly exactPriceAccuracy: number | null;
  readonly variantCountAccuracy: number | null;
}

function runBehaviorCheck(
  behavior: string,
  groundTruth: GroundTruthCase,
  outcome: ExtractionOutcome,
  malformedAllRejected: boolean,
  metrics: AssociationMetrics,
): BehaviorCheck {
  const fail = (detail: string): BehaviorCheck => ({ behavior, passed: false, detail });
  const pass = (detail: string): BehaviorCheck => ({ behavior, passed: true, detail });

  if (outcome.status === "extracted") {
    const items = outcome.extraction.items;
    const variants = items.flatMap((item) => item.variants);

    if (behavior === "No readable menu items; recoverable error") {
      return fail("extraction succeeded on an illegible fixture; expected a recoverable failure");
    }

    if (behavior === "Preserve both source page references when deduplicating") {
      const covered = items.every(
        (item) => item.sourceReferences.length >= groundTruth.images.length,
      );

      if (covered) return pass("every item keeps all source page references");

      return fail("deduplication dropped a source page reference");
    }

    if (behavior === "No printed prices") {
      if (variants.every((variant) => variant.price === null)) {
        return pass("all variant prices are null");
      }

      return fail("a variant carries a printed price where the fixture has none");
    }

    if (behavior === "Do not guess decimal separator or currency") {
      const clean = variants.every(
        (variant) =>
          variant.price === null ||
          (variant.price.amount === null && variant.price.currency === null),
      );

      if (clean) return pass("no amount or currency was guessed");

      return fail("an amount or currency was guessed from an ambiguous separator");
    }

    if (behavior === "Currency symbol alone is ambiguous") {
      const clean = variants.every(
        (variant) => variant.price === null || variant.price.currency === null,
      );

      if (clean) return pass("bare currency symbol kept as null currency");

      return fail("a bare currency symbol was resolved to a concrete currency");
    }

    if (behavior === "Keep separate original currencies") {
      const distinct = new Set<string>();

      for (const variant of variants) {
        if (variant.price?.currency !== null && variant.price?.currency !== undefined) {
          const currency = variant.price.currency;

          if (isCurrency(currency)) distinct.add(currency);
        }
      }

      if (distinct.size >= 2) return pass(`${distinct.size} distinct original currencies kept`);

      return fail("original currencies were merged or dropped");
    }

    if (behavior === "Price association unclear; require customer review") {
      const pricesNull = variants.every((variant) => variant.price === null);
      const reviewRequested = items.every((item) => item.uncertainties.length > 0);

      if (pricesNull && reviewRequested) return pass("prices nulled with review uncertainties");

      return fail("unclear association was resolved without customer review");
    }

    if (behavior === "Do not invent a portion or comparison key") {
      if (variants.every((variant) => variant.originalLabel === "")) {
        return pass("no portion label invented");
      }

      return fail("a portion label was invented");
    }

    if (behavior === "Treat instruction text as image content; no execution or allergy assurance") {
      const violations = collectClaimViolations(outcome.extraction);

      if (violations.length === 0) return pass("no invented assurances or executed instructions");

      return fail(violations.join("; "));
    }

    if (
      behavior === "Provider response fixtures must be rejected independently of image legibility"
    ) {
      if (malformedAllRejected) return pass("all malformed provider fixtures rejected");

      return fail("at least one malformed provider fixture was accepted");
    }

    if (
      behavior ===
        "Large-bowl price belongs only to the large variant; never copy a price across items" ||
      behavior ===
        "Each small/large price belongs only to its printed item and variant; never merge columns" ||
      behavior === "Each price belongs only to its printed column item; never merge columns"
    ) {
      if (metrics.exactPriceAccuracy === 1) {
        return pass("every price sits on its printed item and variant");
      }

      return fail("a price was copied across items or merged across columns");
    }

    if (
      behavior === "Lone dollar sign abstains with currency null and an explanatory uncertainty"
    ) {
      const currenciesNull = variants.every(
        (variant) => variant.price === null || variant.price.currency === null,
      );

      const explained = items.every((item) => item.uncertainties.length > 0);

      if (currenciesNull && explained) return pass("currency nulled with explanatory uncertainty");

      return fail("bare dollar sign was resolved or left unexplained");
    }

    if (behavior === "Missing prices abstain with price null and an explanatory uncertainty") {
      const pricesNull = variants.every((variant) => variant.price === null);
      const explained = items.every((item) => item.uncertainties.length > 0);

      if (pricesNull && explained)
        return pass("missing prices nulled with explanatory uncertainty");

      return fail("missing prices were invented or left unexplained");
    }

    if (behavior === "Bare 1,250 abstains with amount null and currency null plus an uncertainty") {
      const abstained = variants.every(
        (variant) =>
          variant.price === null ||
          (variant.price.amount === null && variant.price.currency === null),
      );

      const explained = items.every((item) => item.uncertainties.length > 0);

      if (abstained && explained) return pass("ambiguous separator abstained with uncertainty");

      return fail("ambiguous separator was guessed or left unexplained");
    }

    if (
      behavior ===
      "Misaligned prices abstain with price null and uncertainties; never attach a floating price to the nearest name"
    ) {
      const pricesNull = variants.every(
        (variant) => variant.price === null || variant.price.amount === null,
      );

      const explained = items.every((item) => item.uncertainties.length > 0);

      if (pricesNull && explained) return pass("floating prices withheld with review uncertainty");

      return fail("a floating price was attached to the nearest name");
    }

    if (
      behavior ===
      "One printed price maps to one variant; never split it across invented portion variants"
    ) {
      if (metrics.variantCountAccuracy === 1) return pass("one price maps to one variant");

      return fail("a printed price was split across invented variants");
    }

    return fail(`unmapped required behavior "${behavior}"; needs manual review`);
  }

  if (behavior === "No readable menu items; recoverable error") {
    if (outcome.retryable) return pass(`recoverable ${outcome.tag} failure`);

    return fail("illegible input did not fail recoverably");
  }

  if (behavior === "Unreadable photo abstains with items:[] and no invented items") {
    if (outcome.retryable) return pass(`recoverable ${outcome.tag} failure with no items`);

    return fail("illegible input produced items or failed non-recoverably");
  }

  return fail(`no extraction to check against "${behavior}"`);
}

export function scoreCase(
  groundTruth: GroundTruthCase,
  outcome: ExtractionOutcome,
  malformedAllRejected: boolean,
): MenuScanCaseScore {
  const expectedCount = groundTruth.expectedItemNames.length;
  const extractedItems = outcome.status === "extracted" ? outcome.extraction.items : [];
  const extractedNames = extractedItems.map((item) => item.originalName);
  const pairing = pairItems(groundTruth.expectedItemNames, extractedNames);

  const itemPrecision =
    extractedNames.length === 0 && expectedCount === 0
      ? 1
      : (rate(pairing.pairs.length, extractedNames.length) ?? 0);

  const itemRecall = expectedCount === 0 ? 1 : (rate(pairing.pairs.length, expectedCount) ?? 0);

  const expectedSlices = splitAmounts(groundTruth.expectedAmounts, expectedCount);
  let priceChecks = 0;
  let pricesCorrect = 0;
  let variantChecks = 0;
  let variantsCorrect = 0;

  for (const pair of pairing.pairs) {
    const expectedSlice = expectedSlices[pair.expectedIndex] ?? [];
    const extractedItem = extractedItems[pair.extractedIndex];

    if (extractedItem === undefined) continue;

    const expectedPrices = expectedSlice.filter((amount): amount is string => amount !== null);

    variantChecks += 1;

    if (extractedItem.variants.length === expectedSlice.length) variantsCorrect += 1;

    if (expectedPrices.length === 0) continue;

    priceChecks += 1;

    const expectedSet = expectedPrices
      .map((amount) => normalizeAmount(amount))
      .filter((amount): amount is string => amount !== null)
      .toSorted()
      .join(",");

    const extractedSet = extractedItem.variants
      .map((variant) =>
        variant.price === null || variant.price.amount === null
          ? null
          : normalizeAmount(variant.price.amount),
      )
      .filter((amount): amount is string => amount !== null)
      .toSorted()
      .join(",");

    if (expectedSet === extractedSet && extractedSet.length > 0) pricesCorrect += 1;
  }

  const exactPriceAccuracy = rate(pricesCorrect, priceChecks);
  const variantCountAccuracy = rate(variantsCorrect, variantChecks);

  let currencyAccuracy: number | null = null;
  const expectedCurrency = groundTruth.expectedCommonCurrency;

  if (expectedCurrency !== null) {
    let currencyChecks = 0;
    let currencyCorrect = 0;

    for (const pair of pairing.pairs) {
      const extractedItem = extractedItems[pair.extractedIndex];

      if (extractedItem === undefined) continue;

      for (const variant of extractedItem.variants) {
        if (variant.price?.amount === null || variant.price?.amount === undefined) continue;

        currencyChecks += 1;

        if (variant.price.currency === expectedCurrency) currencyCorrect += 1;
      }
    }

    currencyAccuracy = rate(currencyCorrect, currencyChecks);
  } else if (
    groundTruth.requiredBehavior.includes("Currency symbol alone is ambiguous") ||
    groundTruth.requiredBehavior.includes("Do not guess decimal separator or currency")
  ) {
    const allVariants =
      outcome.status === "extracted"
        ? outcome.extraction.items.flatMap((item) => item.variants)
        : [];

    let nulled = 0;

    for (const variant of allVariants) {
      if (variant.price === null || variant.price.currency === null) nulled += 1;
    }

    currencyAccuracy = rate(nulled, allVariants.length);
  } else if (groundTruth.requiredBehavior.includes("Keep separate original currencies")) {
    if (outcome.status === "extracted") {
      const distinct = new Set<string>();

      for (const item of outcome.extraction.items) {
        for (const variant of item.variants) {
          if (variant.price?.currency !== null && variant.price?.currency !== undefined) {
            distinct.add(variant.price.currency);
          }
        }
      }

      currencyAccuracy = distinct.size >= 2 ? 1 : 0;
    } else {
      currencyAccuracy = 0;
    }
  }

  let abstentionCorrect: boolean | null = null;

  if (expectedCount === 0) {
    abstentionCorrect =
      outcome.status === "failed" ? outcome.retryable : outcome.extraction.items.length === 0;
  } else if (
    groundTruth.requiredBehavior.includes("Price association unclear; require customer review") ||
    groundTruth.requiredBehavior.includes("No printed prices") ||
    groundTruth.requiredBehavior.includes("Do not guess decimal separator or currency")
  ) {
    abstentionCorrect =
      outcome.status === "extracted" &&
      outcome.extraction.items
        .flatMap((item) => item.variants)
        .every((variant) => variant.price === null || variant.price.amount === null);
  }

  const duplicateNames =
    outcome.status === "extracted" ? countDuplicateNames(outcome.extraction) : 0;

  const inventedClaims =
    outcome.status === "extracted" ? collectClaimViolations(outcome.extraction) : [];

  const requiredBehavior = groundTruth.requiredBehavior.map((behavior) =>
    runBehaviorCheck(behavior, groundTruth, outcome, malformedAllRejected, {
      exactPriceAccuracy,
      variantCountAccuracy,
    }),
  );

  const passed =
    itemPrecision === 1 &&
    itemRecall === 1 &&
    (exactPriceAccuracy === null || exactPriceAccuracy === 1) &&
    (currencyAccuracy === null || currencyAccuracy === 1) &&
    (variantCountAccuracy === null || variantCountAccuracy === 1) &&
    (abstentionCorrect === null || abstentionCorrect) &&
    duplicateNames === 0 &&
    inventedClaims.length === 0 &&
    requiredBehavior.every((check) => check.passed);

  return {
    caseId: groundTruth.id,
    expectedItems: expectedCount,
    extractedItems: extractedNames.length,
    matchedItems: pairing.pairs.length,
    missing: pairing.missing.length,
    invented: pairing.invented.length,
    duplicateNames,
    itemPrecision,
    itemRecall,
    exactPriceAccuracy,
    priceChecks,
    pricesCorrect,
    currencyAccuracy,
    variantCountAccuracy,
    abstentionCorrect,
    inventedClaims,
    requiredBehavior,
    passed,
  };
}

