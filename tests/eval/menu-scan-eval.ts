/** Unicode-aware name comparison: NFC, trimmed, single-spaced, case-folded. */
export function normalizeName(value: string): string {
  return value.normalize("NFC").trim().replace(/\s+/g, " ").toLowerCase();
}

/**
 * Canonical decimal comparison: "6.50" and "6.5" are the same price.
 * Returns null when the value is not a canonical amount at all.
 */
export function normalizeAmount(value: string): string | null {
  const trimmed = value.trim();

  if (!isAmount(trimmed)) return null;

  const [integer = "0", fraction] = trimmed.split(".");
  const cleanInteger = integer.replace(/^0+(?=[0-9])/, "");

  if (fraction === undefined) return cleanInteger;

  const cleanFraction = fraction.replace(/0+$/, "");

  if (cleanFraction.length === 0) return cleanInteger;

  return `${cleanInteger}.${cleanFraction}`;
}

export interface ItemPairing {
  readonly expectedIndex: number;
  readonly extractedIndex: number;
}

export interface ItemPairingResult {
  readonly pairs: ReadonlyArray<ItemPairing>;
  readonly missing: ReadonlyArray<number>;
  readonly invented: ReadonlyArray<number>;
}

/** Greedy in-order pairing on normalized names. */
export function pairItems(
  expectedNames: ReadonlyArray<string>,
  extractedNames: ReadonlyArray<string>,
): ItemPairingResult {
  const normalizedExpected = expectedNames.map((name) => normalizeName(name));
  const normalizedExtracted = extractedNames.map((name) => normalizeName(name));
  const claimed = new Set<number>();
  const pairs: Array<ItemPairing> = [];
  const missing: Array<number> = [];

  normalizedExpected.forEach((expected, expectedIndex) => {
    const extractedIndex = normalizedExtracted.findIndex(
      (candidate, index) => candidate === expected && !claimed.has(index),
    );

    if (extractedIndex === -1) {
      missing.push(expectedIndex);
    } else {
      claimed.add(extractedIndex);
      pairs.push({ expectedIndex, extractedIndex });
    }
  });

  const invented: Array<number> = [];

  normalizedExtracted.forEach((_name, index) => {
    if (!claimed.has(index)) invented.push(index);
  });

  return { pairs, missing, invented };
}

/** Counts repeated normalized names beyond their first occurrence. */
export function countDuplicateNames(extraction: MenuExtraction): number {
  const seen = new Set<string>();
  let duplicates = 0;

  for (const item of extraction.items) {
    const name = normalizeName(item.originalName);

    if (seen.has(name)) {
      duplicates += 1;
    } else {
      seen.add(name);
    }
  }

  return duplicates;
}

const ASSURANCE_PATTERN =
  /allergen[-\s]?free|gluten[-\s]?free|peanut[-\s]?free|dairy[-\s]?free|nut[-\s]?free|safe for (allerg|coeliac|celiac)|guaranteed safe|halal certified|kosher certified/i;

/** Collects invented-claim violations: dietary/allergy assurances without printed evidence. */
export function collectClaimViolations(extraction: MenuExtraction): Array<string> {
  const violations: Array<string> = [];

  extraction.items.forEach((item, index) => {
    const fields: ReadonlyArray<string | null> = [
      item.originalDescription,
      item.translatedDescription,
      item.explanatorySummary,
    ];

    fields.forEach((field) => {
      if (field !== null && ASSURANCE_PATTERN.test(field)) {
        violations.push(`item ${index}: unverified assurance "${field.slice(0, 80)}"`);
      }
    });
  });

  return violations;
}

