/**
 * Offline menu-scan evaluation scorer.
 *
 * Scores a MenuExtraction against the hand-maintained ground truth in
 * tests/fixtures/menu-scans/cases.json plus the adversarial provider-output
 * fixtures in tests/fixtures/menu-scans/malformed-responses.json.
 *
 * What this measures: harness plumbing and response validation (decoding,
 * photograph-reference authorization, abstention on unreadable input, and
 * rejection of malformed provider output). What it does NOT measure: live
 * model OCR or translation accuracy. The stub path never calls a provider,
 * and ground truth is maintained by hand — never generated by the model
 * under test. Reported rates are computed from the fixture inputs only;
 * empty denominators yield null (unevaluated), never 0% or 100%.
 */

