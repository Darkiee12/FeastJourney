function providerContentAccepted(content: string): boolean {
  try {
    const envelopeFormat = z.object({
      choices: z
        .array(
          z.object({
            finish_reason: z.literal("stop"),
            message: z.object({ content: z.string().min(1), refusal: z.null() }),
          }),
        )
        .length(1),
    });

    const parsed = envelopeFormat.safeParse(
      JSON.parse(
        `{"choices":[{"finish_reason":"stop","message":{"content":${JSON.stringify(content)},"refusal":null}}]}`,
      ),
    );

    if (!parsed.success) return false;

    const choice = parsed.data.choices[0];

    if (choice === undefined) return false;

    try {
      const valid = menuExtractionSchema.safeParse(JSON.parse(choice.message.content)).success;

      return valid && templateItemCountValid(choice.message.content);
    } catch {
      return false;
    }
  } catch {
    return false;
  }
}

function providerEnvelopeAccepted(raw: string): boolean {
  try {
    const envelopeFormat = z.object({
      choices: z
        .array(
          z.object({
            finish_reason: z.string(),
            message: z.object({ content: z.string(), refusal: z.string().nullable().optional() }),
          }),
        )
        .length(1),
    });

    const parsed = envelopeFormat.safeParse(JSON.parse(raw));

    if (!parsed.success) return false;

    const choice = parsed.data.choices[0];

    if (choice === undefined || choice.finish_reason !== "stop" || choice.message.refusal) {
      return false;
    }

    return (
      menuExtractionSchema.safeParse(JSON.parse(choice.message.content)).success &&
      templateItemCountValid(choice.message.content)
    );
  } catch {
    return false;
  }
}

/** Empty item lists are a recoverable abstention, never a successful extraction. */
function templateItemCountValid(content: string): boolean {
  try {
    const itemsFormat = z.object({ items: z.array(z.unknown()).min(1) });

    return itemsFormat.safeParse(JSON.parse(content)).success;
  } catch {
    return false;
  }
}

export interface PriceProbe {
  readonly rawText: string;
  readonly amount: string | number;
  readonly currency: string | null;
}

function injectedPriceRejected(probe: PriceProbe): boolean {
  const template = templateExtraction();
  const item = template.items[0];

  if (item === undefined) return false;

  const variant = item.variants[0];

  if (variant === undefined) return false;

  const candidate = {
    ...template,
    items: [
      {
        ...item,
        variants: [
          {
            ...variant,
            price: {
              rawText: probe.rawText,
              amount: probe.amount,
              currency: probe.currency,
              taxTreatment: "unknown" as const,
            },
          },
        ],
      },
    ],
  };

  return !menuExtractionSchema.safeParse(candidate).success;
}

export interface MalformedCheck {
  readonly name: string;
  readonly kind: "rejection" | "detection" | "live-only";
  readonly rejected: boolean | null;
  readonly detail: string;
}

export interface MalformedReport {
  readonly checks: ReadonlyArray<MalformedCheck>;
  readonly evaluated: number;
  readonly rejected: number;
  readonly unevaluated: number;
  readonly allRejected: boolean;
}

export function scoreMalformedFixtures(fixtures: MalformedFixtures): MalformedReport {
  const checks: Array<MalformedCheck> = [];

  const rejection = (name: string, rejected: boolean, detail: string): void => {
    checks.push({ name, kind: "rejection", rejected, detail });
  };

  rejection(
    "truncated-envelope",
    !providerEnvelopeAccepted(JSON.stringify(fixtures.truncated)),
    "truncated provider output must fail envelope validation",
  );

  for (const payload of fixtures.fakePayloads) {
    const accepted =
      payload.kind === "content"
        ? providerContentAccepted(payload.content)
        : providerEnvelopeAccepted(payload.content);

    rejection(`fake-payload:${payload.id}`, !accepted, payload.expectedBehavior);
  }

  rejection(
    "foreign-photograph-reference",
    !new Set([TEMPLATE_ASSET_ID]).has(fixtures.foreignAssetId),
    "references to unauthorized photograph IDs must be rejected after schema validation",
  );

  rejection(
    "unsupported-currency",
    injectedPriceRejected({
      rawText: "price",
      amount: "1",
      currency: fixtures.unsupportedCurrency,
    }),
    `currency ${fixtures.unsupportedCurrency} must fail ISO validation`,
  );

  rejection(
    "numeric-json-amount",
    injectedPriceRejected({
      rawText: "price",
      amount: fixtures.numericAmount,
      currency: "USD",
    }),
    "JSON number amounts must fail transport validation",
  );

  rejection(
    "invalid-decimal",
    injectedPriceRejected({
      rawText: fixtures.invalidDecimal,
      amount: fixtures.invalidDecimal,
      currency: "EUR",
    }),
    "guessed separator decimals must fail canonical amount validation",
  );

  rejection(
    "executable-output",
    !providerContentAccepted(fixtures.unexpectedExecutableOutput),
    "markup content is never valid extraction JSON and is never rendered",
  );

  for (const quantity of fixtures.impossibleQuantities) {
    rejection(
      `impossible-quantity:${quantity.id}`,
      injectedPriceRejected({
        rawText: quantity.rawText,
        amount: quantity.amount,
        currency: quantity.currency,
      }),
      quantity.note,
    );
  }

  for (const symbol of fixtures.misleadingCurrencySymbols) {
    if (symbol.judgment === "schema-reject") {
      rejection(
        `misleading-symbol:${symbol.id}`,
        injectedPriceRejected({
          rawText: symbol.rawText,
          amount: symbol.amount,
          currency: symbol.currency,
        }),
        symbol.note,
      );
    } else {
      checks.push({
        name: `misleading-symbol:${symbol.id}`,
        kind: "live-only",
        rejected: null,
        detail: `${symbol.note} Requires live inference; unevaluated offline.`,
      });
    }
  }

  const repeated: MenuExtraction = {
    ...templateExtraction(),
    items: fixtures.repeatedNames.names.map((name, index) => ({
      originalName: name,
      translatedName: null,
      originalDescription: null,
      translatedDescription: null,
      explanatorySummary: null,
      ingredients: null,
      variants: [
        {
          originalLabel: "",
          translatedLabel: null,
          price: {
            rawText: fixtures.repeatedNames.amounts[index] ?? "",
            amount: fixtures.repeatedNames.amounts[index] ?? null,
            currency: "VND",
            taxTreatment: "unknown" as const,
          },
        },
      ],
      sourceReferences: [{ assetId: TEMPLATE_ASSET_ID, region: null }],
      uncertainties: [],
    })),
  };

  checks.push({
    name: "repeated-names",
    kind: "detection",
    rejected: countDuplicateNames(repeated) > 0,
    detail: fixtures.repeatedNames.note,
  });

  for (const override of fixtures.instructionOverrides) {
    checks.push({
      name: `instruction-override:${override.id}`,
      kind: "live-only",
      rejected: null,
      detail: `${override.expectedBehavior} Requires live inference; unevaluated offline.`,
    });
  }

  const evaluated = checks.filter((check) => check.kind !== "live-only");
  const rejected = evaluated.filter((check) => check.rejected === true);

  return {
    checks,
    evaluated: evaluated.length,
    rejected: rejected.length,
    unevaluated: checks.length - evaluated.length,
    allRejected: evaluated.length > 0 && rejected.length === evaluated.length,
  };
}

export interface SensitivityProbe {
  readonly probe: string;
  readonly metric: string;
  readonly value: number | null;
  readonly detected: boolean;
  readonly detail: string;
}

export interface ScoredCase {
  readonly groundTruth: GroundTruthCase;
  readonly outcome: ExtractionOutcome;
  readonly score: MenuScanCaseScore;
}

export interface EvalSummary {
  readonly mode: "stub" | "live";
  readonly liveEvaluation: "run" | "not_run";
  readonly model: string;
  readonly caseCount: number;
  readonly casesPassed: number;
  readonly microPrecision: number | null;
  readonly microRecall: number | null;
  readonly totals: {
    readonly expectedItems: number;
    readonly extractedItems: number;
    readonly matchedItems: number;
    readonly missing: number;
    readonly invented: number;
  };
  readonly exactPriceAccuracy: number | null;
  readonly currencyAccuracy: number | null;
  readonly variantCountAccuracy: number | null;
  readonly abstentionApplicable: number;
  readonly abstentionCorrect: number;
  readonly malformed: MalformedReport;
  readonly sensitivityProbes: ReadonlyArray<SensitivityProbe>;
  readonly cases: ReadonlyArray<MenuScanCaseScore>;
  readonly groundTruthNote: string;
  readonly liveInferenceNote: string;
}

export function summarizeEvaluation(
  mode: "stub" | "live",
  model: string,
  liveEvaluation: "run" | "not_run",
  scored: ReadonlyArray<ScoredCase>,
  malformed: MalformedReport,
  probes: ReadonlyArray<SensitivityProbe>,
): EvalSummary {
  let expectedItems = 0;
  let extractedItems = 0;
  let matchedItems = 0;
  let missing = 0;
  let invented = 0;
  let casesPassed = 0;
  let abstentionApplicable = 0;
  let abstentionCorrect = 0;

  for (const entry of scored) {
    expectedItems += entry.score.expectedItems;
    extractedItems += entry.score.extractedItems;
    matchedItems += entry.score.matchedItems;
    missing += entry.score.missing;
    invented += entry.score.invented;

    if (entry.score.passed) casesPassed += 1;

    if (entry.score.abstentionCorrect !== null) {
      abstentionApplicable += 1;

      if (entry.score.abstentionCorrect) abstentionCorrect += 1;
    }
  }

  return {
    mode,
    liveEvaluation,
    model,
    caseCount: scored.length,
    casesPassed,
    microPrecision: rate(matchedItems, extractedItems) ?? (expectedItems === 0 ? 1 : 0),
    microRecall: rate(matchedItems, expectedItems) ?? 1,
    totals: { expectedItems, extractedItems, matchedItems, missing, invented },
    exactPriceAccuracy: meanOrNull(scored.map((entry) => entry.score.exactPriceAccuracy)),
    currencyAccuracy: meanOrNull(scored.map((entry) => entry.score.currencyAccuracy)),
    variantCountAccuracy: meanOrNull(scored.map((entry) => entry.score.variantCountAccuracy)),
    abstentionApplicable,
    abstentionCorrect,
    malformed,
    sensitivityProbes: probes,
    cases: scored.map((entry) => entry.score),
    groundTruthNote:
      "Ground truth is hand-maintained in tests/fixtures/menu-scans/cases.json and was never generated by the model under test.",
    liveInferenceNote:
      liveEvaluation === "run"
        ? "Live provider inference ran for this summary; see per-case latency metadata."
        : "Live provider inference did NOT run for this summary; stub results validate harness plumbing only.",
  };
}

function formatRate(value: number | null): string {
  if (value === null) return "  -   ";

  return value.toFixed(2).padStart(6, " ");
}

function formatFlag(value: boolean | null): string {
  if (value === null) return "  -  ";

  return value ? "  ok  " : " FAIL ";
}

export function formatCaseTable(summary: EvalSummary): string {
  const lines: Array<string> = [
    `menu-scan eval (${summary.mode}, model ${summary.model}, live: ${summary.liveEvaluation})`,
    "case                      P      R    price   curr    var   abst  claims  verdict",
  ];

  for (const score of summary.cases) {
    const claims = score.inventedClaims.length === 0 ? "  ok  " : " FAIL ";

    lines.push(
      `${score.caseId.padEnd(24, " ")} ${formatRate(score.itemPrecision)} ${formatRate(score.itemRecall)} ${formatRate(score.exactPriceAccuracy)} ${formatRate(score.currencyAccuracy)} ${formatRate(score.variantCountAccuracy)} ${formatFlag(score.abstentionCorrect)} ${claims}  ${score.passed ? "PASS" : "FAIL"}`,
    );
  }

  lines.push(
    `cases ${summary.casesPassed}/${summary.caseCount} passed | ` +
      `micro P ${formatRate(summary.microPrecision)} R ${formatRate(summary.microRecall)} | ` +
      `malformed ${summary.malformed.rejected}/${summary.malformed.evaluated} rejected ` +
      `(${summary.malformed.unevaluated} live-only)`,
  );

  return lines.join("\n");
}

export function summaryToJson(summary: EvalSummary): string {
  return JSON.stringify(summary, null, 2);
}
