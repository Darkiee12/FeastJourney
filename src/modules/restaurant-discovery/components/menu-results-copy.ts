const translations: ReadonlyMap<string, typeof english> = new Map([
  ["en", english],
  ["vi", vietnamese],
  ["hi", hindi],
  ["es", spanish],
  ["zh", chinese],
  ["ja", japanese],
  ["de", german],
  ["nl", dutch],
]);

export const menuResultsCopy = (locale: string): typeof english =>
  translations.get(locale) ?? english;

/** Locale-aware plural selection and number formatting stay in the translation boundary. */
export function menuResultsCount(
  locale: string,
  kind: keyof typeof english.counts,
  count: number,
): string {
  const resolved = translations.has(locale) ? locale : "en";
  const forms = menuResultsCopy(resolved).counts[kind];
  const category = new Intl.PluralRules(resolved).select(count);
  const template = category === "one" ? forms.one : forms.other;

  return template.replace("{count}", new Intl.NumberFormat(resolved).format(count));
}
